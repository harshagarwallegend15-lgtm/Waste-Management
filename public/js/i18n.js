  /* ---- Google Fonts for scripts requiring special fonts ---- */
  function loadFont(lang) {
    if (lang === 'ta' || lang === 'bn' || lang === 'hi' || lang === 'kn') {
      if (!document.querySelector('link[href*="Noto+Sans"]')) {
        var link = document.createElement('link');
        link.rel = 'stylesheet';
        link.href = 'https://fonts.googleapis.com/css2?family=Noto+Sans:wght@400;600;700&display=swap';
        document.head.appendChild(link);
      }
    }
  }

  /* ---- Translation lookup ---- */
  function t(key, params) {
    var str = (translations[currentLang] && translations[currentLang][key]) ||
              (translations[DEFAULT_LANG] && translations[DEFAULT_LANG][key]) ||
              key;
    if (params) {
      Object.keys(params).forEach(function (p) {
        str = str.replace(new RegExp('\\{' + p + '\\}', 'g'), params[p]);
      });
    }
    return str;
  }

  /* ---- DOM translation ---- */
  function translateDOM() {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (key) el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      if (key) el.innerHTML = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      if (key) el.placeholder = t(key);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-title');
      if (key) el.title = t(key);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-aria');
      if (key) el.setAttribute('aria-label', t(key));
    });
  }

  /* ---- Set language ---- */
  function setLang(lang) {
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
    loadFont(lang);
    translateDOM();
    document.dispatchEvent(new CustomEvent('ww:i18n', { detail: { lang: lang } }));
  }

  /* ---- Get language ---- */
  function getLang() {
    return currentLang;
  }

  /* ---- Public API ---- */
  window.WWI18n = {
    t: t,
    setLang: setLang,
    getLang: getLang,
    translateDOM: translateDOM,
    LANGUAGES: LANGUAGES
  };

  /* ---- Also expose t globally ---- */
  window.t = t;

  /* ---- Auto-init ---- */
  function init() {
    loadFont(currentLang);
    document.documentElement.lang = currentLang;
    translateDOM();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

